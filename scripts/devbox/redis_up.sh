#!/usr/bin/env bash
# task redis:up 入口：确保监督器与数据目录 → 启用 Redis → 轮询就绪 → 输出摘要
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/services.sh"

cd "${PROJECT_ROOT}"

WAIT_TIMEOUT_SEC=30

is_redis_ready() {
  redis-cli ping 2>/dev/null | grep -q PONG
}

print_summary() {
  local port="${REDIS_PORT:-6379}"
  echo "Redis 已就绪；端口: ${port}；逻辑库: 0（dev）/ 1（test）"
}

# ---------------------------------------------------------------------------
# 1. 确保监督器（含 Redis 数据目录 db-data/redis 创建）
# ---------------------------------------------------------------------------
ensure_supervisor

# ---------------------------------------------------------------------------
# 2. 已就绪：仅输出摘要
# ---------------------------------------------------------------------------
if is_redis_ready; then
  print_summary
  exit 0
fi

# ---------------------------------------------------------------------------
# 3. 启用本库进程
# ---------------------------------------------------------------------------
start_service redis

# ---------------------------------------------------------------------------
# 4. 就绪轮询（进程已启动 ≠ 服务已就绪）
# ---------------------------------------------------------------------------
for i in $(seq 1 "${WAIT_TIMEOUT_SEC}"); do
  if is_redis_ready; then
    break
  fi
  if [ "${i}" -eq "${WAIT_TIMEOUT_SEC}" ]; then
    echo "Redis 在 ${WAIT_TIMEOUT_SEC} 秒内未就绪，请查看 .devbox/virtenv/redis/redis.log" >&2
    exit 1
  fi
  sleep 1
done

# ---------------------------------------------------------------------------
# 5. 输出摘要
# ---------------------------------------------------------------------------
print_summary
