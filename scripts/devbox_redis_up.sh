#!/usr/bin/env bash
# task redis:up 入口：启动 devbox Redis → 轮询就绪 → 输出摘要
set -euo pipefail

# ---------------------------------------------------------------------------
# 配置
# ---------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
WAIT_TIMEOUT_SEC=30

cd "${PROJECT_ROOT}"

# ---------------------------------------------------------------------------
# 工具函数
# ---------------------------------------------------------------------------
is_redis_ready() {
  redis-cli ping | grep -q PONG
}

print_summary() {
  local port="${REDIS_PORT:-6379}"
  echo "Redis 已就绪；端口: ${port}；逻辑库: 0（dev）/ 1（test）"
}

# ---------------------------------------------------------------------------
# 1. 已就绪：仅输出摘要
# ---------------------------------------------------------------------------
if is_redis_ready; then
  print_summary
  exit 0
fi

# ---------------------------------------------------------------------------
# 2. 服务启动
# ---------------------------------------------------------------------------
echo "启动 Redis..."
devbox services up redis -b -q >/dev/null 2>&1

# ---------------------------------------------------------------------------
# 3. 就绪轮询（进程已启动 ≠ 服务已就绪）
# ---------------------------------------------------------------------------
for i in $(seq 1 "${WAIT_TIMEOUT_SEC}"); do
  if is_redis_ready; then
    break
  fi
  if [ "${i}" -eq "${WAIT_TIMEOUT_SEC}" ]; then
    echo "Redis 在 ${WAIT_TIMEOUT_SEC} 秒内未就绪，请查看 .devbox/virtenv/redis/redis.log" >&2
    exit 1
  fi
  sleep 1
done

# ---------------------------------------------------------------------------
# 4. 输出摘要
# ---------------------------------------------------------------------------
print_summary
